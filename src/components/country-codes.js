/**
 * Convierte un código de país ISO 3166-1 alpha-2 a su nombre en español
 * @param {string} code - Código de país de dos letras
 * @returns {string} Nombre del país en español o el código original si no se encuentra
 */
export const getCountryName = (code) => {
  if (!code) return '';
  const normalizedCode = code.toUpperCase();
  return countryCodeToName[normalizedCode] || code;
};
